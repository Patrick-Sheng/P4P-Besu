#!/usr/bin/env node
'use strict';

// Generates a Caliper benchmark config with one round per TPS level, each
// round pointing at its own pre-sliced voter-pool chunk (see slice-voters.js
// for why rounds can't share one votersFile). Used for the Area-1 node-count
// x TPS sweep.
//
// Usage: node gen-sweep-yaml.js <nodeCount> <outFile> <durationSeconds> <workers> <tps1> [<tps2> ...]

const fs = require('node:fs');

const [, , nodeCountArg, outFileArg, durationArg, workersArg, ...tpsArgs] = process.argv;
const nodeCount = parseInt(nodeCountArg, 10);
const duration = parseInt(durationArg, 10);
const workers = parseInt(workersArg, 10);
const tpsList = tpsArgs.map(Number);

if (!nodeCount || !outFileArg || !duration || !workers || tpsList.length === 0) {
    console.error('Usage: node gen-sweep-yaml.js <nodeCount> <outFile> <durationSeconds> <workers> <tps1> [<tps2> ...]');
    process.exit(1);
}

const rounds = tpsList.map((tps, i) => `    - label: sweep-n${nodeCount}-${tps}tps
      description: n=${nodeCount} validators, target ${tps} TPS, round ${i}
      txDuration: ${duration}
      rateControl:
        type: fixed-rate
        opts:
          tps: ${tps}
      workload:
        module: workloads/cast-vote.js
        arguments:
          votersFile: seed/generated/n${nodeCount}-sweep-r${i}.json
          numCandidates: 3`).join('\n');

const yaml = `## Generated by seed/gen-sweep-yaml.js -- Area 1 node-count x TPS sweep.
## n=${nodeCount} validators, TPS ladder: ${tpsList.join(', ')}, ${duration}s/round.
test:
  workers:
    number: ${workers}
  rounds:
${rounds}
`;

fs.writeFileSync(outFileArg, yaml);
console.log(`Wrote ${outFileArg} (${tpsList.length} rounds, round index 0..${tpsList.length - 1} <-> TPS ${tpsList.join(',')})`);
