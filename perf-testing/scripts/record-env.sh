#!/bin/bash
# T0 - records the test environment before any additional-test run
# (docs/Additional Test Plan Infrastructure Evaluation.md). Read-only: runs
# inspection commands only - starts no network, no load, changes nothing.
# The additional-test drivers copy this file into every run directory.
#
# Usage: scripts/record-env.sh [outFile=reports/additional/env.txt]
# Then fill in the "by hand" section at the end (hypervisor allocation, host).
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."   # -> perf-testing/

OUT="${1:-reports/additional/env.txt}"
mkdir -p "$(dirname "$OUT")"
if [ -f "$OUT" ]; then
    mv "$OUT" "${OUT%.txt}-$(date '+%Y%m%d-%H%M%S').prev.txt"
fi

run() {  # prints the command, then its output (stderr included - java -version writes there)
    echo "\$ $*"
    bash -c "$*" 2>&1
    local rc=$?
    [ "$rc" -ne 0 ] && echo "(exit ${rc})"
    echo
}

{
    echo "# T0 environment record - $(date '+%F %T %z') - $(hostname)"
    echo "# generated by perf-testing/scripts/record-env.sh"
    echo
    echo "## Commands from the test plan"
    run 'nproc'
    run 'lscpu | grep -E "Model name|^CPU\(s\)"'
    run 'free -h'
    run 'uname -a'
    run 'cat /proc/version          # contains "microsoft" if running in WSL'
    run 'systemd-detect-virt        # VM/container type, or "none"'
    run 'df -h network/generated 2>/dev/null || df -h .   # disk holding the validator data'
    run 'java -version'
    run 'besu --version'
    # MemoryMax is a property of the transient validator unit: it only exists
    # while a run is active. Otherwise each run.log has a "Memory budget" line.
    if systemctl --user list-units --plain --no-legend 'p4p-besu-*' 2>/dev/null | grep -q .; then
        for u in $(systemctl --user list-units --plain --no-legend 'p4p-besu-*' | awk '{print $1}'); do
            run "systemctl --user show ${u} -p MemoryMax"
        done
    else
        echo "\$ systemctl --user show p4p-besu-n4-v1 -p MemoryMax"
        echo "(no p4p-besu-* unit is running now - per-validator MemoryMax/heap are logged as 'Memory budget' in every run.log)"
        echo
    fi

    echo "## Extra context used by the harness"
    run 'lscpu'
    run 'grep -E "MemTotal|MemAvailable|SwapTotal" /proc/meminfo'
    run 'swapon --show'
    run 'cat /sys/fs/cgroup/cgroup.controllers   # cgroup v2 + memory controller needed for MemoryMax'
    run 'systemctl --version | head -1'
    run 'besu --help 2>/dev/null | grep -i -A2 -- "--tx-pool"   # T2: confirm the pool option names'
    run 'source ~/.nvm/nvm.sh >/dev/null 2>&1; nvm use 22 >/dev/null 2>&1; node --version'
    run 'jq --version'
    run 'curl --version | head -1'
    run 'git -C .. rev-parse HEAD; git -C .. status --short | head -20'

    cat <<'EOF'
## Fill in by hand
VM / hypervisor (e.g. VirtualBox, VMware, Hyper-V, none):
VM vCPU allocation:
VM memory allocation (GB):
VM disk type (SSD/HDD, virtual disk format):
Host laptop CPU model and core/thread count:
Host laptop total RAM (GB):
Host OS:
Other heavy processes running on the host during tests:
EOF
} > "$OUT"

echo "Wrote ${OUT} - now fill in its 'Fill in by hand' section."
